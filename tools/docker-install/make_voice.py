"""Generate the AI voice-over for the "Docker Installation" video.

One MP3 per script line (so every scene can sync exactly to its line),
then writes src/DockerInstall/voice.ts with each clip's duration.

Run:  python -I tools/docker-install/make_voice.py
Needs: pip install edge-tts   (uses Microsoft Edge online neural voices)
"""
import asyncio
import json
import subprocess
import sys
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "public" / "docker-install" / "voice"
TS_OUT = ROOT / "src" / "DockerInstall" / "voice.ts"

VOICE = "en-IN-PrabhatNeural"  # natural Indian English male voice
RATE = "+8%"

# id, exact script line (shown in code for reference), spoken form for TTS.
# Spoken form only changes HOW commands are pronounced, never the words.
LINES = [
    ("hey", "Hey everyone!", "Hey everyone!"),
    ("containers", "Want to run applications inside containers without installing everything manually?",
     "Want to run applications inside containers, without installing everything manually?"),
    ("letsInstall", "Let's install Docker on Windows in less than a minute!",
     "Let's install Docker on Windows, in less than a minute!"),
    ("browser", "First, open your browser and search for Docker Desktop.",
     "First, open your browser, and search for Docker Desktop."),
    ("download", "Visit the official Docker website and download Docker Desktop for Windows.",
     "Visit the official Docker website, and download Docker Desktop for Windows."),
    ("installer", "Once the download is complete, open the installer and follow the setup instructions.",
     "Once the download is complete, open the installer, and follow the setup instructions."),
    ("wsl", "Make sure the WSL 2 option is enabled when prompted.",
     "Make sure the W S L 2 option is enabled, when prompted."),
    ("restart", "After installation, restart your computer if required.",
     "After installation, restart your computer, if required."),
    ("engine", "Open Docker Desktop and wait until the Docker Engine is running.",
     "Open Docker Desktop, and wait until the Docker Engine is running."),
    ("version", "Now, open your terminal and run this command: docker --version.",
     "Now, open your terminal, and run this command: docker, dash dash version."),
    ("helloWorld", "To verify that Docker is working properly, run: docker run hello-world.",
     "To verify that Docker is working properly, run: docker run hello world."),
    ("congrats", "If you see the Hello from Docker message, congratulations!",
     "If you see the Hello from Docker message... congratulations!"),
    ("installed", "Docker is successfully installed.", "Docker is successfully installed."),
    ("thatsIt", "That's it! You've successfully installed Docker on Windows.",
     "That's it! You've successfully installed Docker on Windows."),
    ("follow", "Follow me for more simple DevOps tutorials, and let's learn Docker step by step!",
     "Follow me for more simple DevOps tutorials, and let's learn Docker, step by step!"),
]


def duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return float(out)


async def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    result = []
    for line_id, script, spoken in LINES:
        raw = OUT_DIR / f"{line_id}.raw.mp3"
        target = OUT_DIR / f"{line_id}.wav"
        await edge_tts.Communicate(spoken, VOICE, rate=RATE).save(str(raw))
        # Trim leading/trailing silence so scene timing follows the actual speech.
        trim = ("silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.04,"
                "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse")
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(raw), "-af", trim,
                        "-ar", "48000", "-ac", "1", str(target)], check=True)
        raw.unlink()
        secs = duration(target)
        result.append({"id": line_id, "file": f"docker-install/voice/{line_id}.wav",
                       "seconds": round(secs, 3), "script": script})
        print(f"{line_id:12s} {secs:6.2f}s  {script}")

    body = json.dumps(result, indent=2)
    TS_OUT.write_text(
        "// AUTO-GENERATED by tools/docker-install/make_voice.py — do not edit by hand.\n"
        "export type VoiceLine = {id: string; file: string; seconds: number; script: string};\n\n"
        f"export const VOICE_LINES: VoiceLine[] = {body};\n",
        encoding="utf-8",
    )
    print("total speech:", round(sum(r["seconds"] for r in result), 2), "s")


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
