"""Generate the AI voice-over for the "Electric Heated Gloves" ad.

One MP3 per script line (so every scene can sync exactly to its line),
then writes src/DockerInstall/voice.ts with each clip's duration.

Run:  python -I tools/heated-gloves/make_voice.py
Needs: pip install edge-tts   (uses Microsoft Edge online neural voices)
"""
import asyncio
import json
import subprocess
import sys
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "public" / "heated-gloves" / "voice"
TS_OUT = ROOT / "src" / "HeatedGloves" / "voice.ts"

VOICE = "en-IN-PrabhatNeural"  # natural Indian English male voice
RATE = "+8%"

# id, exact script line (shown in code for reference), spoken form for TTS.
# Spoken form only changes HOW commands are pronounced, never the words.
LINES = [
    ("frozen", "Are your hands always freezing during winter?", "Are your hands always freezing during winter?"),
    ("cool", "Here's a cool little product you need to check out!", "Here's a cool little product, you need to check out!"),
    ("these", "These are electric heated gloves!", "These are electric heated gloves!"),
    ("designed", "They're designed to help keep your hands warm when the temperature drops.",
     "They're designed to help keep your hands warm, when the temperature drops."),
    ("features", "They come with a USB connection for heating, and the touchscreen-friendly design lets you use your smartphone without taking them off.",
     "They come with a U S B connection for heating, and the touchscreen-friendly design lets you use your smartphone, without taking them off."),
    ("colors", "And look at these different colors and styles!", "And look at these different colors and styles!"),
    ("choose", "You can choose the design that matches your style.", "You can choose the design that matches your style."),
    ("guess", "And guess what?", "And guess what?"),
    ("price", "They're just five dollars at Walmart!", "They're just five dollars, at Walmart!"),
    ("budget", "That's a budget-friendly winter find!", "That's a budget-friendly winter find!"),
    ("checkout", "Check them out at Walmart, and don't forget to share this with someone who always has cold hands!",
     "Check them out at Walmart, and don't forget to share this with someone, who always has cold hands!"),
]


def duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return float(out)


async def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    result = []
    for line_id, script, spoken in LINES:
        raw = OUT_DIR / f"{line_id}.raw.mp3"
        target = OUT_DIR / f"{line_id}.wav"
        await edge_tts.Communicate(spoken, VOICE, rate=RATE).save(str(raw))
        # Trim leading/trailing silence so scene timing follows the actual speech.
        trim = ("silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.04,"
                "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse")
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(raw), "-af", trim,
                        "-ar", "48000", "-ac", "1", str(target)], check=True)
        raw.unlink()
        secs = duration(target)
        result.append({"id": line_id, "file": f"heated-gloves/voice/{line_id}.wav",
                       "seconds": round(secs, 3), "script": script})
        print(f"{line_id:12s} {secs:6.2f}s  {script}")

    body = json.dumps(result, indent=2)
    TS_OUT.write_text(
        "// AUTO-GENERATED by tools/heated-gloves/make_voice.py — do not edit by hand.\n"
        "export type VoiceLine = {id: string; file: string; seconds: number; script: string};\n\n"
        f"export const VOICE_LINES: VoiceLine[] = {body};\n",
        encoding="utf-8",
    )
    print("total speech:", round(sum(r["seconds"] for r in result), 2), "s")


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
